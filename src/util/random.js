'use strict';
// Seedable PRNG (mulberry32) so plan/scheduler logic is unit-testable.
function mulberry32(seed) {
  let a = seed >>> 0;
  return function () {
    a = (a + 0x6D2B79F5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
function hashString(s) {
  let h = 2166136261;
  for (let i = 0; i < s.length; i++) { h ^= s.charCodeAt(i); h = Math.imul(h, 16777619); }
  return h >>> 0;
}
const randInt = (rng, min, max) => Math.floor(rng() * (max - min + 1)) + min;
const randFloat = (rng, min, max) => rng() * (max - min) + min;
function shuffle(arr, rng = Math.random) {
  const a = arr.slice();
  for (let i = a.length - 1; i > 0; i--) { const j = Math.floor(rng() * (i + 1)); [a[i], a[j]] = [a[j], a[i]]; }
  return a;
}
const sleep = ms => new Promise(r => setTimeout(r, ms));
module.exports = { mulberry32, hashString, randInt, randFloat, shuffle, sleep };
